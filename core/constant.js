// ============================================================================
// chat-optimization-v2 可调常数集中定义。
// 所有影响行为/性能的可调常数集中在本文件，每个常数附调整指导。
// 必须最先加载（见 index.js MODULES 顺序），其余模块经 NS.Constants 读取。
//
// 分组规则：按功能域分组（分层摘要 / prompt 组装 / UI），
// 域内按子关注点分小节；同一功能域跨模块的常数相邻放置，小节头标注来源模块。
//
// 不集中（保留在各自模块，因为不是"可调常数"）：
//   - 标识型字符串：存储键（HIER_METADATA_KEY / TAB_STORAGE_KEY 等）、
//     DOM id、版本号（index.js VERSION）
//   - 产品数据：默认模板、FIRST_MESSAGE_SUFFIX、wordMapping、
//     模板占位符（DAY/MERGE_PLACEHOLDER）、UI 标签、ERASE_ALL_CONFIRM_TEXT
//   - 用户可配置项：settings.js defaultSettings（keepCount / tokenLimit /
//     hierFanin / hierDayPrompt 等，运行时经 Settings.get 读取）
// ============================================================================
(function () {
    'use strict';

    const NS = window.ChatOptimizationV2 = window.ChatOptimizationV2 || {};

    NS.Constants = Object.freeze({
        // ==================================================================
        // 【分层摘要】后台生成（subsummary.js）。
        // L1 天摘要 ← 当天 L0 条目；L(k≥2) ← 连续 fanin 个 L(k-1) 合并。
        // 发送前永不等 LLM，缺失父节点由装配层用子节点原文兜底。
        // ==================================================================

        // ------------------------------------------------------------------
        // 分层摘要 · 生成与重试（subsummary.js）
        // ------------------------------------------------------------------

        // 单次摘要生成失败后的最大重试次数（不含首次）。
        MAX_RETRIES: 3,

        // 每次重试前的等待（毫秒）。总等待上限 = MAX_RETRIES × 本值；
        // 目标 API 有限流时调大，减少连续失败。
        RETRY_DELAY_MS: 1000,

        // 单次 LLM 请求超时（毫秒），fetch / profile 双通道共用。
        // 无超时的 await 是卡死主因：服务端 hang 住（连接接受但永不返回）时
        // runOneWithRetry 永远等不到成功或失败，批次卡在某一条、running 永不复位，
        // 后续批次经 batchChain 排在其后也被堵住。超时后按失败走 MAX_RETRIES 重试。
        // 实际生效值读设置项 subSummaryTimeoutSec（秒），非法时回退到本值；
        // 本地慢模型（CPU 推理 512 token 可能数分钟）→ 把设置项调大。
        SUBSUMMARY_REQUEST_TIMEOUT_MS: 120000,

        // subSummaryTimeoutSec 的钳制下限/上限（毫秒）。
        // 下限太小会把慢模型正常推理误判为超时；上限太大则卡住时等太久。
        SUBSUMMARY_TIMEOUT_MIN_MS: 10000,
        SUBSUMMARY_TIMEOUT_MAX_MS: 600000,

        // 批量生成期间状态进度通知的最小间隔（毫秒，trailing 节流）：
        // 每条完成后都会尝试通知，但两次实际通知间隔不足本值时合并到下一次，
        // 保证批量结束时最后一条进度不丢失；批次终态（成功/失败汇总）不受节流、
        // 始终立即通知。UI 每收到一次进度通知都会更新状态行，
        // 故本值同时决定 UI 进度刷新频率。
        // 调大 → 大批量时 UI 更新更少、主线程更空闲；调小 → 进度更实时。
        SUBSUMMARY_STATUS_NOTIFY_INTERVAL_MS: 300,

        // 批量生成并行 worker 数上限（subsummary.js executeBatch worker 池的 clamp 上限）。
        // LLM 调用主要是 IO 等待，并行省的是等待时间；直连 / profile API 都有服务端限流，
        // 并行过高易触发 429（靠 MAX_RETRIES 重试兜底）。日常调并发改设置项
        // subSummaryConcurrency（分层摘要 tab），不动本值。
        SUBSUMMARY_CONCURRENCY_MAX: 8,

        // ------------------------------------------------------------------
        // 分层摘要 · 层级结构（subsummary.js / engine.js）
        // ------------------------------------------------------------------

        // L(k≥2) 合并的扇入下限/上限：连续几个 L(k-1) 节点合并成一条父摘要。
        // 实际扇入读设置项 hierFanin，非法时回退 HIER_FANIN_DEFAULT；
        // 本值只做钳制。扇入越大层数越浅、单次合并输入越长；
        // 扇入越小层数越深、后台生成调用次数越多。
        HIER_FANIN_MIN: 2,
        HIER_FANIN_MAX: 10,

        // 非法 hierFanin 时的回退扇入（须落在 MIN..MAX 内）。
        HIER_FANIN_DEFAULT: 5,

        // 最大层级数（含 L1）。天数极多时封顶，避免无限向上合并；
        // 达到上限后最旧侧整节点丢弃（由装配层执行，不再生成更高层）。
        HIER_MAX_LEVELS: 4,

        // 未知天数组（天数无法解析的条目）的展示标签。
        // 仅 UI/装配展示用，不参与摘要输入输出。
        HIER_UNKNOWN_DAY_LABEL: '未知天',

        // ==================================================================
        // 【prompt 组装】折叠装箱与角色卡处理（engine.js）。
        // ==================================================================

        // ------------------------------------------------------------------
        // prompt 组装 · 折叠估算（engine.js buildPromptData）
        // ------------------------------------------------------------------

        // 折叠估算常数（1 token ≈ N 个汉字），仅用于折叠前的贪心估算；
        // 折叠后用 getTokenCountAsync 精确计数，超预算从最旧节点逐个丢弃（无次数上限），
        // 故最终 token 上限不受本值影响，只影响切分点选择与精确计数调用次数。
        // 调小 → 估算更保守，候选少、更快，但可能过度折叠；
        // 调大 → 估算更乐观，精确计数调用变多（更慢）。
        // 中文内容合理区间约 1.2~2.0。
        EST_CHARS_PER_TOKEN: 1.5,

        // ------------------------------------------------------------------
        // prompt 组装 · 故事块解析缓存（engine.js getFloorStoryBlock / subsummary.js）
        // ------------------------------------------------------------------

        // 楼层故事块解析结果缓存条目上限。
        // 缓存按 (mes 引用 + 当前 swipe 文本引用) 双重校验有效性，
        // 消息内容变化（含 in-place 改 mes、切 swipe）自动失效重解析。
        // 仅影响内存（每楼层一份解析对象/哈希），与解析结果正确性无关，
        // 调大/调小均不改变最终渲染与召回结果。
        STORY_PARSE_CACHE_MAX: 4096,

        // ------------------------------------------------------------------
        // prompt 组装 · 角色卡淘汰（engine.js processCharacterData）
        // ------------------------------------------------------------------

        // 角色卡槽位上限，超出的角色被物理删除（不写入 prompt）。
        // 每张卡核心设定约数百 token；调大增加 token 消耗，
        // 仅当角色很多且模型上下文宽裕时再调。
        ROLE_CARD_MAX_SLOTS: 10,

        // 最新用户消息提及的角色的得分（保证保留且不被丢弃）。
        // 只需"显著大于任何可能的聊天下标"，无需调整。
        ROLE_CARD_MENTION_SCORE: 1000000,

        // 久未活跃丢弃阈值：角色超过 N 条消息未活跃（且非当前提问提及）时，
        // 直接从本次发送的角色卡中丢弃（不保留蒸馏空壳，避免模板已删除字段的空对象污染 prompt）。
        // 调大 → 更多久未出场角色保留，token 消耗更高；
        // 调小 → 出场阵容更精简，久未出场角色更快消失。
        ROLE_CARD_STALE_DISTANCE: 100,

        // ==================================================================
        // 【UI】界面交互（ui/coo-window.js）。
        // ==================================================================

        // ------------------------------------------------------------------
        // UI · 魔杖菜单挂载（ui/coo-window.js）
        // ------------------------------------------------------------------

        // 扩展菜单入口挂载失败时的重试间隔（毫秒）。
        MENU_RETRY_INTERVAL_MS: 500,

        // 最大重试次数（总等待 = 间隔 × 次数 = 15 秒）。
        // ST 启动慢/菜单 DOM 出现晚时可调大。
        MENU_RETRY_MAX_ATTEMPTS: 30,

        // 点击扩展菜单按钮后延迟重挂载入口（毫秒），
        // 等 ST 自己的菜单重建逻辑执行完。
        MENU_REMOUNT_DELAY_MS: 100,

        // ==================================================================
        // 【角色状态追踪】逐楼层可变状态（roletrack.js）。
        // 每次助手回复后以后台对本楼层 L0（该回复的 NEW_HISTORY 条目）调一次
        // 独立 LLM 连接，结果数组存该楼层 extra，装配角色卡时按楼层顺序合并。
        // 重试/超时与分层摘要同口径（MAX_RETRIES / RETRY_DELAY_MS /
        // SUBSUMMARY_REQUEST_TIMEOUT_MS 复用）。
        // ==================================================================

        // ------------------------------------------------------------------
        // 角色状态追踪 · 输入与输出上限（roletrack.js）
        // ------------------------------------------------------------------

        // 单次追踪输入的故事历程字符上限：本楼层 L0 经 entryToDocText 拼接后
        // 超过本值时从最旧侧截断（保留尾部），保证单次 LLM 输入可控。
        // 调大 → 超长单楼层历程保留更全，token 消耗更高；
        // 调小 → 输入更省，长楼层可能丢最旧条目。
        ROLETRACK_JOURNEY_MAX_CHARS: 12000,

        // 单楼层追踪输出的角色数上限：LLM 返回数组超长时只保留前 N 项
        // （按返回顺序），防止异常输出污染过多角色状态。
        // 调大 → 单楼层允许更多角色同时变化；调小 → 更保守。
        ROLETRACK_TRACKS_MAX_PER_FLOOR: 10,

        // 批量补齐缺失追踪时的并行 worker 数上限（roletrack.js executeBatch
        // worker 池的 clamp 上限）。语义同 SUBSUMMARY_CONCURRENCY_MAX：
        // LLM 调用主要是 IO 等待，并行省等待时间；过高易触发 429
        // （靠 MAX_RETRIES 重试兜底）。日常调并发改设置项
        // roleTrackConcurrency（角色状态 tab），不动本值。
        ROLETRACK_CONCURRENCY_MAX: 8,

        // ------------------------------------------------------------------
        // UI · NEW_STORY_DATA 解析失败气泡（ui/coo-window.js，engine.js 广播）
        // ------------------------------------------------------------------

        // 解析失败气泡自动隐藏的延迟（毫秒）。
        // 失败楼层多、原因文字长时调大，留足阅读时间；觉得打扰就调小。
        PARSE_FAIL_BUBBLE_TIMEOUT_MS: 8000,
    });
})();
