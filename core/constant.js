// ============================================================================
// chat-optimization-v2 可调常数集中定义。
// 所有影响行为/性能的可调常数集中在本文件，每个常数附调整指导。
// 必须最先加载（见 index.js MODULES 顺序），其余模块经 NS.Constants 读取。
//
// 分组规则：按功能域分组（二级摘要 / BM25 / prompt 组装 / UI），
// 域内按子关注点分小节；同一功能域跨模块的常数（如二级摘要跨
// subsummary.js / engine.js / recallcache.js）相邻放置，小节头标注来源模块。
//
// 不集中（保留在各自模块，因为不是"可调常数"）：
//   - 标识型字符串：存储键（EXTRA_KEY / METADATA_KEY / TAB_STORAGE_KEY 等）、
//     DOM id、模型与 WASM 资源路径（MODEL_ID / *_REL）、版本号（index.js VERSION）
//   - 产品数据：默认模板、FIRST_MESSAGE_SUFFIX、wordMapping、QUERY_INSTRUCTION、
//     PLACEHOLDER、UI 标签、ERASE_ALL_CONFIRM_TEXT
//   - 用户可配置项：settings.js defaultSettings（keepCount / tokenLimit /
//     ragRatio / subSummary* 等，运行时经 Settings.get 读取）
// ============================================================================
(function () {
    'use strict';

    const NS = window.ChatOptimizationV2 = window.ChatOptimizationV2 || {};

    NS.Constants = Object.freeze({
        // ==================================================================
        // 【二级摘要】核心功能：后台生成 → 发送前补生成等待 → Mode A 召回打分
        // → 打分缓存与后台预热，由本地向量化与持久化支撑
        // （embedding.js / embedstore.js 目前仅服务本功能）。
        // 跨 subsummary.js / engine.js / recallcache.js / embedding.js / embedstore.js。
        // ==================================================================

        // ------------------------------------------------------------------
        // 二级摘要 · 生成与发送前补生成等待（subsummary.js / engine.js）
        // ------------------------------------------------------------------

        // 单条摘要生成失败后的最大重试次数（不含首次）。
        MAX_RETRIES: 3,

        // 每次重试前的等待（毫秒）。总等待上限 = MAX_RETRIES × 本值；
        // 目标 API 有限流时调大，减少连续失败。
        RETRY_DELAY_MS: 1000,

        // 发送前补生成缺失二级摘要的最长等待（毫秒）。
        // 超时不取消后台批次，本次用已有摘要继续打分（缺失条目不参与本次召回）。
        // 连接慢且能接受更长的发送延迟 → 调大；希望快速发出 → 调小。
        SUBSUMMARY_WAIT_TIMEOUT_MS: 30000,

        // 批量生成期间状态进度通知的最小间隔（毫秒，trailing 节流）：
        // 每条完成后都会尝试通知，但两次实际通知间隔不足本值时合并到下一次，
        // 保证批量结束时最后一条进度不丢失；批次终态（成功/失败汇总）不受节流、
        // 始终立即通知。UI 每收到一次进度通知都会更新状态行并增量刷新对应条目，
        // 故本值同时决定 UI 进度刷新频率。
        // 调大 → 大批量时 UI 更新更少、主线程更空闲；调小 → 进度更实时。
        SUBSUMMARY_STATUS_NOTIFY_INTERVAL_MS: 300,

        // ------------------------------------------------------------------
        // 二级摘要 · 召回打分（engine.js scoreFarEntries / scoreFarEntriesModeA）
        // ------------------------------------------------------------------

        // v2.18.0 起分数不再有可调权重：
        // 命中门槛——(片段, 条目) 的 S_actor=0 且 S_location=0 → 该片段对该条目记 0 分（未命中）；
        // 命中则 fragScore = S_semantic = max(S_event, S_recall)（纯语义排序）。
        // S_actor（Dice）与 S_location（命中比例）仅作为门槛信号，不再进入总分。
        // user 信息片段不受门槛限制（总是按 S_semantic 计分）；
        // 窗口片段与 Mode B 查询视为非 user 信息，受门槛限制。
        // 门槛命中过严（大量条目 0 分）时，检查摘要 actor/location 是否与当前查询习惯脱节
        // （如地点命名过细导致 queryText.includes(loc) 难命中）。


        // ------------------------------------------------------------------
        // 二级摘要 · 召回打分 Mode A 片段权重（engine.js scoreFarEntriesModeA）
        // ------------------------------------------------------------------

        // Mode A 片段权重（相对权重，只有比值有意义）：
        // 片段 = 最新用户消息 + 窗口历程条目（最新→次新→…），
        // 各片段与条目摘要分别打分后按权重加权取 max。
        // 窗口权重越低 → 召回越"由用户提问驱动"，仅凭近期上下文不易触发召回；
        // 越高 → 近期窗口自身也能触发召回（更主动，但也更吵）。
        // 建议全部 ≤ 1.0，避免上下文片段盖过用户提问信号。

        // 最新用户消息片段权重（锚点，原则上不动，改它等价于整体缩放）。
        FRAG_WEIGHT_USER: 1.1,
        // 最新窗口条目片段权重（窗口权重的基准值）。
        FRAG_WEIGHT_WIN_BASE: 1.0,
        // 窗口权重衰减因子：第 i 条（最新 i=0）权重 = FRAG_WEIGHT_WIN_BASE × FRAG_WEIGHT_WIN_DECAY^i。
        // 调小 → 旧窗口条目影响衰减越快，召回越由最新消息驱动；调大 → 旧条目保留更多话语权。
        FRAG_WEIGHT_WIN_DECAY: 0.95,
        // 窗口权重下限：权重（含衰减）低于该值的条目直接跳过，且因权重单调递减，
        // 其后续更旧的条目一并停止参与 farEntries 打分。
        // 调高 → 参与打分的窗口条目更少（更快、更聚焦）；调低 → 更多旧条目参与（更慢、更宽）。
        FRAG_WEIGHT_WIN_MIN: 0.50,

        // ------------------------------------------------------------------
        // 二级摘要 · 打分缓存与后台预热（recallcache.js）
        // ------------------------------------------------------------------

        // 进页面后首次后台预热的延迟（毫秒）。
        WARMUP_FIRST_DELAY_MS: 1000,

        // 收到消息后的预热防抖窗口（毫秒）。
        WARMUP_DEBOUNCE_MS: 2000,

        // 预热时最多取最近 N 个楼层条目的 event 预编码其片段向量。
        // 调大 → 首次发送时更多片段向量已就绪（更快），后台编码负担更重。
        WARMUP_WINDOW_PREVIEW: 16,

        // 片段向量 LRU 容量（用户消息 / 窗口条目 event 的 query 指令向量，
        // 512 float ≈ 2KB/条）。
        FRAG_VEC_CAP: 4096,

        // 条目文档向量 LRU 容量（每槽 = 摘要 event 1 条 + recall_when 数条向量）。
        DOC_VEC_CAP: 4096,

        // (片段, 条目) 对分数 LRU 容量。键是片段×条目的笛卡尔积，三者中增长最快；
        // 调大 → 切换聊天/摘要重生成后更少重算，注意内存（每槽为小对象）。
        PAIR_SCORE_CAP: 262144,

        // ------------------------------------------------------------------
        // 二级摘要 · 向量化支撑：本地 embedding（embedding.js）
        // ------------------------------------------------------------------

        // 内存向量 LRU 容量（精确文本键）。
        // 每向量 512 float ≈ 2KB，2048 ≈ 4MB。
        // 调大 → 减少跨发送/跨楼层的重复编码，代价是内存。
        CACHE_MAX: 2048,

        // 批量推理大小。调大 → 批量预热更快，但单次调用延迟与峰值内存更高；
        // 调小 → 后台运行更平滑。
        BATCH_SIZE: 16,

        // 是否优先 WebGPU（fp32 模型）加速推理。
        // true → 浏览器支持 WebGPU 时加载 onnx/model.onnx（fp32，约 95MB）在 GPU 上推理；
        // WebGPU 不可用或模型/会话创建失败时自动回退 q8/WASM（行为不变），
        // 召回功能不中断（fp32 与 q8 向量数值差异可忽略，无需清空向量库）。
        // WebGPU EP 不支持 int8 量化 GEMM，q8 模型走 GPU 无加速意义，故 GPU 路径必须用 fp32。
        // false → 始终 q8/WASM。遇到 WebGPU 兼容问题（驱动/浏览器限制）或想省模型加载时关闭。
        EMBED_USE_WEBGPU: false,

        // ------------------------------------------------------------------
        // 二级摘要 · 向量化支撑：向量持久化同步（embedstore.js）
        // ------------------------------------------------------------------

        // 进页面后首次完整性同步的延迟（毫秒），
        // 等 Embedder 预热与聊天数据就绪。数据加载慢的环境可调大。
        EMBED_SYNC_FIRST_DELAY_MS: 1000,

        // 收到消息后的同步防抖窗口（毫秒），批量消息只触发一次同步。
        EMBED_SYNC_DEBOUNCE_MS: 2000,

        // ==================================================================
        // 【BM25】Mode B 召回通道（二级摘要关闭时启用）：
        // 分词、打分、检索、回退分归一化。跨 retrieval.js / engine.js。
        // ==================================================================

        // ------------------------------------------------------------------
        // BM25 · 分词、检索与回退打分（retrieval.js / engine.js）
        // ------------------------------------------------------------------

        // 单字停用虚词表（只过滤单字形态；包含它们的 bigram 照常产出，如"在校"保留）。
        // 可按故事语料追加高频虚词（如文言"之乎者也"之外的语气字）；
        // 承载语义的字（不/没/有 等否定、存在词）不可加入，否则会破坏召回。
        STOP_UNI: '的了着在和与及或是等都就还又很太更最被把让向对从到为之其此该这那它我你他她吗吧啊呀嘛呢么'.split(''),

        // BM25 词频饱和参数。越大 → 词在文档中重复出现带来的增量权重衰减越快；
        // 标准值 1.2~2.0。
        BM25_K1: 1.5,

        // BM25 文档长度归一化。1 = 完全归一化（长条目被更多惩罚），0 = 不归一化。
        // 远端条目长度差异大（单条 vs 按天聚合多条），保持标准值附近。
        BM25_B: 0.75,

        // Retriever.retrieve 的默认 topK。
        // engine 始终显式传入候选池大小，本值仅作为直接调用/测试的缺省。
        DEFAULT_TOP_K: 6,

        // BM25 候选收集阈值（未归一化分）。0 = 收集所有有词项命中的条目。
        // 调大（如 1~3）会过滤弱相关候选，减少召回段噪音与装箱计算；
        // 调得过高会漏掉"语义相关但字面重叠弱"的条目。
        // 仅在 Mode B（二级摘要关闭）生效，Mode A 不走 BM25。
        RAG_MIN_SCORE: 0,

        // BM25 回退分数饱和归一化常数：norm = score / (score + K) ∈ [0,1)。
        // K 越小曲线越快饱和，弱命中的相对分越高（召回更"粗"、区分度下降）；
        // K 越大分数梯度越平缓。
        // 保持与远端条目典型原始 BM25 分（通常几~几十）同量级即可。
        BM25_NORM_K: 4,

        // ==================================================================
        // 【prompt 组装】召回段装箱与角色卡处理（engine.js）。
        // ==================================================================

        // ------------------------------------------------------------------
        // prompt 组装 · 召回段装箱（engine.js buildPromptData）
        // ------------------------------------------------------------------

        // 召回段装箱估算常数（1 token ≈ N 个汉字），仅用于装箱前的贪心估算；
        // 装箱后用 getTokenCountAsync 精确计数，超预算从最低分逐条剔除（无次数上限），
        // 故最终 token 上限不受本值影响，只影响装箱速度与候选装填量。
        // 调小 → 估算更保守，候选少、更快，但可能装不满预算；
        // 调大 → 估算更乐观，精确计数调用变多（更慢）。
        // 中文内容合理区间约 1.2~2.0。
        EST_CHARS_PER_TOKEN: 1.5,

        // ------------------------------------------------------------------
        // prompt 组装 · 故事块解析缓存（engine.js getFloorStoryBlock / subsummary.js storyHash）
        // ------------------------------------------------------------------

        // 楼层故事块解析结果缓存条目上限（同一常数也用作 subsummary.js
        // storyHash 缓存上限，两者同以楼层消息对象为键）。
        // 缓存按 (mes 引用 + 当前 swipe 文本引用) 双重校验有效性，
        // 消息内容变化（含 in-place 改 mes、切 swipe）自动失效重解析。
        // 仅影响内存（每楼层一份解析对象/哈希），与解析结果正确性无关，
        // 调大/调小均不改变最终渲染与召回结果。
        STORY_PARSE_CACHE_MAX: 4096,

        // ------------------------------------------------------------------
        // prompt 组装 · 角色卡淘汰与蒸馏（engine.js processCharacterData）
        // ------------------------------------------------------------------

        // 角色卡槽位上限，超出的角色被物理删除（不写入 prompt）。
        // 每张卡核心设定约数百 token；调大增加 token 消耗，
        // 仅当角色很多且模型上下文宽裕时再调。
        ROLE_CARD_MAX_SLOTS: 10,

        // 最新用户消息提及的角色的得分（保证保留且不被蒸馏）。
        // 只需"显著大于任何可能的聊天下标"，无需调整。
        ROLE_CARD_MENTION_SCORE: 1000000,

        // 蒸馏距离阈值：角色超过 N 条消息未活跃（且非当前提问提及）时，
        // 只保留核心设定（剔除穿戴/物品/技能等动态高消耗字段）。
        // 调大 → 蒸馏更宽松（更多动态字段保留，token 消耗更高）；
        // 调小 → 压缩更激进。
        ROLE_CARD_STALE_DISTANCE: 30,

        // ==================================================================
        // 【UI】界面交互（ui/coo-window.js）。
        // ==================================================================

        // ------------------------------------------------------------------
        // UI · 魔杖菜单挂载（ui/coo-window.js）
        // ------------------------------------------------------------------

        // 扩展菜单入口挂载失败时的重试间隔（毫秒）。
        MENU_RETRY_INTERVAL_MS: 500,

        // 最大重试次数（总等待 = 间隔 × 次数 = 15 秒）。
        // ST 启动慢/菜单 DOM 出现晚时可调大。
        MENU_RETRY_MAX_ATTEMPTS: 30,

        // 点击扩展菜单按钮后延迟重挂载入口（毫秒），
        // 等 ST 自己的菜单重建逻辑执行完。
        MENU_REMOUNT_DELAY_MS: 100,

        // ------------------------------------------------------------------
        // UI · NEW_STORY_DATA 解析失败气泡（ui/coo-window.js，engine.js 广播）
        // ------------------------------------------------------------------

        // 解析失败气泡自动隐藏的延迟（毫秒）。
        // 失败楼层多、原因文字长时调大，留足阅读时间；觉得打扰就调小。
        PARSE_FAIL_BUBBLE_TIMEOUT_MS: 8000,
    });
})();
